from __future__ import annotations

from src.shared.qt import QHBoxLayout, QLabel, QProgressBar, QPushButton, QTableWidget, QTextEdit, QFrame, QSizePolicy, QVBoxLayout
from src.ui.features.annotation.ai.mapping import configure_mapping_table


def build_result_layout(dialog, root):
    mapping_card = QFrame()
    mapping_card.setObjectName("card")
    mapping_card.setSizePolicy(QSizePolicy.Policy.Expanding, QSizePolicy.Policy.Expanding)
    mapping_layout = QVBoxLayout(mapping_card)
    mapping_layout.setContentsMargins(12, 10, 12, 10)
    mapping_layout.setSpacing(6)
    mapping_header = QHBoxLayout()
    mapping_header.setContentsMargins(0, 0, 0, 0)
    mapping_title = QLabel("类别映射")
    mapping_title.setObjectName("sectionTitle")
    mapping_header.addWidget(mapping_title)
    mapping_header.addStretch(1)
    dialog.mapping_summary = QLabel("等待加载模型类别")
    dialog.mapping_summary.setObjectName("fieldLabel")
    mapping_header.addWidget(dialog.mapping_summary)
    mapping_layout.addLayout(mapping_header)
    dialog.mapping_table = QTableWidget(0, 4)
    configure_mapping_table(dialog.mapping_table)
    dialog.mapping_table.setSizePolicy(QSizePolicy.Policy.Expanding, QSizePolicy.Policy.Expanding)
    mapping_layout.addWidget(dialog.mapping_table, 1)
    root.addWidget(mapping_card, 4)
    
    progress_card = QFrame()
    progress_card.setObjectName("card")
    progress_card.setSizePolicy(QSizePolicy.Policy.Expanding, QSizePolicy.Policy.Maximum)
    progress_layout = QVBoxLayout(progress_card)
    progress_layout.setContentsMargins(12, 10, 12, 10)
    progress_layout.setSpacing(6)
    progress_header = QHBoxLayout()
    progress_header.setContentsMargins(0, 0, 0, 0)
    progress_title = QLabel("运行进度")
    progress_title.setObjectName("sectionTitle")
    progress_header.addWidget(progress_title)
    dialog.progress_bar = QProgressBar()
    dialog.progress_bar.setRange(0, 100)
    dialog.progress_bar.setValue(0)
    progress_header.addWidget(dialog.progress_bar, 1)
    progress_layout.addLayout(progress_header)
    dialog.progress_log = QTextEdit()
    dialog.page.prepare_readonly_text(dialog.progress_log)
    dialog.progress_log.setMinimumHeight(44)
    dialog.progress_log.setMaximumHeight(88)
    progress_layout.addWidget(dialog.progress_log, 1)
    root.addWidget(progress_card)
    
    button_row = QHBoxLayout()
    button_row.setContentsMargins(0, 2, 0, 0)
    button_row.setSpacing(10)
    button_row.addStretch(1)
    dialog.start_btn = QPushButton("开始预标注")
    dialog.start_btn.clicked.connect(dialog.start_ai_labeling)
    button_row.addWidget(dialog.start_btn)
    dialog.stop_btn = QPushButton("停止标注")
    dialog.stop_btn.setObjectName("softButton")
    dialog.stop_btn.setEnabled(False)
    dialog.stop_btn.clicked.connect(dialog.stop_ai_labeling)
    button_row.addWidget(dialog.stop_btn)
    dialog.undo_btn = QPushButton("删除AI标注")
    dialog.undo_btn.setEnabled(False)
    dialog.undo_btn.clicked.connect(dialog.undo_ai_changes)
    button_row.addWidget(dialog.undo_btn)
    back_btn = QPushButton("返回标注")
    back_btn.setObjectName("softButton")
    back_btn.clicked.connect(dialog.accept)
    button_row.addWidget(back_btn)
    root.addLayout(button_row)



__all__ = ["build_result_layout"]
